#!/usr/bin/env python3
"""Write the licence notices for third-party code that ships with KiVi.

    python3 tools/notices.py                    # THIRD-PARTY-NOTICES.md
    python3 tools/notices.py --check            # exit 1 if it's out of date
    python3 tools/notices.py --appdir DIR OUT   # system libraries in an AppImage

THIRD-PARTY-NOTICES.md covers the vendored JavaScript (vendor/) and every Rust
crate compiled into the app for Linux or Windows, with each crate's licence files as
published on crates.io (MIT and Apache-2.0 require them in binary copies too).
It's committed and bundled with the app; rerun after changing Cargo.lock or
vendor/. It needs `cargo` and the crate sources (`cargo fetch`).

The AppImage also carries ~170 shared libraries (GTK, WebKitGTK, GStreamer…)
that linuxdeploy copies from the build machine, so which ones depends on the
Ubuntu release. `--appdir` maps them to their Debian packages through dpkg's
file lists and writes each package's version, source and copyright file, as
the LGPL and the other licences ask; CI publishes that file with the release.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD-PARTY-NOTICES.md"
# The release builds: the Linux AppImage and the Windows installer.
TARGETS = ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc"]

# Vendored JavaScript: (name, version, licence, homepage, licence file, notes).
VENDORED = [
    ("three.js", "0.169.0", "MIT", "https://threejs.org",
     "vendor/three/LICENSE",
     "`vendor/three/three.module.js` and the addons in `vendor/three/addons/`."),
    ("Chevrotain", "9.0.1", "Apache-2.0", "https://chevrotain.io",
     "vendor/three/addons/libs/chevrotain.LICENSE",
     "`vendor/three/addons/libs/chevrotain.module.min.js`, bundled by three.js for its VRML loader."),
    ("occt-import-js", "0.0.22", "LGPL-2.1", "https://github.com/kovacsv/occt-import-js",
     "vendor/occt-import-js/LICENSE.md",
     "`vendor/occt-import-js/`: Open CASCADE Technology (LGPL-2.1 with the Open CASCADE "
     "exception, https://dev.opencascade.org) compiled to WebAssembly with Emscripten "
     "(MIT). It is loaded as a separate, replaceable file. KiVi modifies "
     "`occt-import-js.js` in one place, marked `KiVi patch` (see `vendor/README.md`); "
     "the modified file is its own source. The unmodified sources are at the homepage."),
]

LICENSE_NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")


def cargo_packages():
    """Crates compiled into the app on any release target (normal and build dependencies), sorted."""
    found = {}
    for target in TARGETS:
        out = subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target,
             "--manifest-path", str(ROOT / "src-tauri" / "Cargo.toml")],
            check=True, capture_output=True, text=True).stdout
        meta = json.loads(out)
        pkgs = {p["id"]: p for p in meta["packages"]}
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        root = meta["resolve"]["root"]
        seen, todo = set(), [root]
        while todo:
            node = nodes[todo.pop()]
            for dep in node["deps"]:
                # dev-dependencies are only built for the crates' own tests.
                if any(k["kind"] != "dev" for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                    seen.add(dep["pkg"])
                    todo.append(dep["pkg"])
        seen.discard(root)
        found.update((i, pkgs[i]) for i in seen)
    return sorted(found.values(), key=lambda p: (p["name"], p["version"]))


def licence_files(pkg):
    """The crate's licence files, from license-file and the usual names in its root."""
    folder = Path(pkg["manifest_path"]).parent
    files = set()
    if pkg.get("license_file"):
        files.add(folder / pkg["license_file"])
    for f in folder.iterdir():
        if f.is_file() and f.name.upper().startswith(LICENSE_NAMES):
            files.add(f)
    return sorted(files, key=lambda f: f.name)


def read_text(path):
    return path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()


def fence(text):
    """A code fence longer than any backtick run in the text."""
    ticks = "```"
    while ticks in text:
        ticks += "`"
    return f"{ticks}text\n{text}\n{ticks}"


def notices():
    out = [
        "# Third-party notices",
        "",
        "KiVi is licensed under the GNU General Public License, version 3 or later",
        "(see `LICENSE`). It includes the third-party software listed below, each under",
        "its own licence. This file is generated by `tools/notices.py`; don't edit it by hand.",
        "",
        "The AppImage additionally bundles shared libraries from the Ubuntu system it was",
        "built on (GTK, WebKitGTK, GStreamer and their dependencies). They are listed, with",
        "their versions, sources and licences, in `appimage-libraries.md`, published with",
        "each release.",
        "",
        "## JavaScript and WebAssembly (vendor/)",
        "",
    ]
    for name, version, lic, home, path, note in VENDORED:
        out += [f"### {name} {version}", "", f"Licence: {lic}. {home}", "", note, "",
                fence(read_text(ROOT / path)), ""]

    pkgs = cargo_packages()
    out += ["## Rust crates", "",
            f"Compiled into the `kivi-desktop` binary for Linux or Windows ({len(pkgs)} crates). Where a crate",
            "offers a choice of licences, KiVi uses it under one compatible with the",
            "GPL-3.0. Each crate's licence files, as published on crates.io, are under",
            "[Crate licence texts](#crate-licence-texts); many crates share the same text,",
            "so each is printed once and the crates refer to it by number. A crate marked",
            "\"none published\" ships no licence file; the standard text of its licence",
            "applies (see the texts here for Apache-2.0, MIT, MPL-2.0 and BSD-3-Clause).", "",
            "| Crate | Version | Licence | Licence texts |", "|---|---|---|---|"]
    texts = {}  # whitespace-insensitive key → (number, text)
    for p in pkgs:
        refs = []
        for f in licence_files(p):
            t = read_text(f)
            refs.append(texts.setdefault(" ".join(t.split()), (len(texts) + 1, t))[0])
        link = f"[{p['name']}]({p['repository']})" if p.get("repository") else p["name"]
        cells = [link, p["version"], (p.get("license") or "see licence text").replace("|", "\\|"),
                 ", ".join(f"[T{n}](#t{n})" for n in sorted(set(refs))) or "none published"]
        out.append("| " + " | ".join(cells) + " |")
    out += ["", "## Crate licence texts", ""]
    for n, t in sorted(texts.values()):
        out += [f"### T{n}", "", fence(t), ""]
    return "\n".join(out).rstrip() + "\n"


def dpkg_owners():
    """Map file path → Debian package, from dpkg's per-package file lists."""
    owners = {}
    info = Path("/var/lib/dpkg/info")
    for lst in info.glob("*.list"):
        pkg = lst.stem
        for line in lst.read_text(errors="replace").splitlines():
            owners.setdefault(line, pkg)
    return owners


def dpkg_field(pkg, field):
    return subprocess.run(["dpkg-query", "-W", "-f", "${" + field + "}", pkg],
                          check=True, capture_output=True, text=True).stdout.strip()


def appimage_libraries(appdir):
    """Markdown listing the Debian packages behind the AppImage's shared libraries."""
    owners = dpkg_owners()
    by_name = {}
    for path, pkg in owners.items():
        by_name.setdefault(os.path.basename(path), pkg)
    pkgs, unknown = set(), []
    for f in sorted(Path(appdir).rglob("*.so*")):
        if not f.is_file():
            continue
        rel = "/" + str(f.relative_to(appdir))
        pkg = owners.get(rel) or by_name.get(f.name)
        if pkg:
            pkgs.add(pkg)
        else:
            unknown.append(rel)
    osr = dict(l.split("=", 1) for l in Path("/etc/os-release").read_text().splitlines() if "=" in l)
    release = osr.get("PRETTY_NAME", "?").strip('"')
    out = [
        "# Libraries bundled in the KiVi AppImage",
        "",
        f"The AppImage includes these shared libraries from {release}, unmodified, so the",
        "app runs on other Linux distributions. KiVi only links to them dynamically; you",
        "may replace them with other versions. Each package's source code is available",
        "from Ubuntu at the Launchpad link given. Each package's copyright file below",
        "lists its copyright holders and licences (mostly LGPL-2.1+, MIT and BSD-style);",
        "the licences they refer to in /usr/share/common-licenses are at the end.",
        "",
        "Generated by `tools/notices.py --appdir`.",
        "",
    ]
    for pkg in sorted(pkgs):
        name = pkg.split(":")[0]
        version = dpkg_field(pkg, "Version")
        source = dpkg_field(pkg, "source:Package") or name
        source_version = dpkg_field(pkg, "source:Version") or version
        copyright_file = Path("/usr/share/doc") / name / "copyright"
        out += [f"## {name} {version}", "",
                f"Source: https://launchpad.net/ubuntu/+source/{source}/{source_version}", ""]
        if copyright_file.is_file():
            out += [fence(read_text(copyright_file)), ""]
        else:
            out += ["(No copyright file installed; see the source package.)", ""]
    if unknown:
        out += ["## Files not from a Debian package", ""] + [f"- `{u}`" for u in unknown] + [""]
    # Debian copyright files point at these instead of including the full text.
    body = "\n".join(out)
    common = Path("/usr/share/common-licenses")
    for name in sorted({m for m in re.findall(r"/usr/share/common-licenses/([A-Za-z0-9.+-]*[A-Za-z0-9+])", body)
                        if (common / m).is_file()}):
        out += [f"## /usr/share/common-licenses/{name}", "", fence(read_text(common / name)), ""]
    return "\n".join(out).rstrip() + "\n", len(pkgs), unknown


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if THIRD-PARTY-NOTICES.md is out of date")
    ap.add_argument("--appdir", nargs=2, metavar=("DIR", "OUT"), help="list an AppDir's system libraries")
    args = ap.parse_args()

    if args.appdir:
        text, count, unknown = appimage_libraries(Path(args.appdir[0]))
        Path(args.appdir[1]).write_text(text)
        print(f"{args.appdir[1]}: {count} packages, {len(unknown)} files without a package")
        return
    text = notices()
    if args.check:
        if not NOTICES.exists() or NOTICES.read_text() != text:
            sys.exit("THIRD-PARTY-NOTICES.md is out of date: run python3 tools/notices.py")
        print("THIRD-PARTY-NOTICES.md is up to date")
        return
    NOTICES.write_text(text)
    print(f"wrote {NOTICES.relative_to(ROOT)} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
